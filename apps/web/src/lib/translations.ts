/**
 * Returns UI translations object for the requested language code with automatic fallback to English for any missing keys.
 */
export function getUITrans(langCode: string = 'en-US') {
  const current = UI_TRANS[langCode] || UI_TRANS['en-US'];
  const fallback = UI_TRANS['en-US'];

  return new Proxy(current, {
    get(target, prop: string) {
      if (prop in target && target[prop]) {
        return target[prop];
      }
      return fallback[prop] ?? '';
    }
  });
}
